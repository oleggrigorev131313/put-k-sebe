export function createSeed(): AppState {
  const practices = ["plan-step", "base-check", "plan-thought", "base-alt", "base-facts", "base-anxiety", "base-observe", "base-critic", "plan-compare"];
  const completionOffsets = [0, 0, 1, 1, 3, 5, 10, 16, 22, 30, 44, 60, 74];
  return {
    onboarded: false,
    entries: demoEntries(),
    patterns: demoPatterns(),
    completions: completionOffsets.map((offset, index) => ({
      id: `c${index + 1}`,
      practiceId: practices[index % practices.length],
      completedAt: atDay(offset, 15 - (index % 4)),
      usefulness: 3 + (index % 3),
      difficultyRating: 2 + (index % 3),
    })),
    suggestions: [],
    settings: defaultSettings(),
    notifications: demoNotifications(),
    analysesUsed: 1,
    analysesDate: todayKey(),
    plan: "free",
    summarySeenDate: null,
    startedPracticeId: null,
    draft: null,
  };
}

export function loadState(): AppState {
  try {
    const raw = localStorage.getItem(STORAGE_KEY);
    if (!raw) return createSeed();
    const parsed = JSON.parse(raw) as AppState;
    if (!parsed || !Array.isArray(parsed.entries) || !parsed.settings) return createSeed();
    return parsed;
  } catch {
    return createSeed();
  }
}

export function analysesUsedToday(state: AppState): number {
  return state.analysesDate === todayKey() ? state.analysesUsed : 0;
}
